// Regenerates src/content/catalog.gen.ts from the page bodies.
//   node scripts/gen-catalog.mjs          write the file
//   node scripts/gen-catalog.mjs --check  exit 1 if the committed file is stale
// Node 22.18+ strips TypeScript types natively; the content files only use type imports.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import prettier from "prettier";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contentDir = path.join(root, "src/content");
const OUT = path.join(contentDir, "catalog.gen.ts");

/** Group files in display order; must match PAGES_BY_GROUP in src/content/index.ts. */
export const GROUP_FILES = [
  ["features.ts", "FEATURE_PAGES"],
  ["use-cases.ts", "USE_CASE_PAGES"],
  ["compare.ts", "COMPARE_PAGES"],
  ["resources.ts", "RESOURCE_PAGES"],
];

export async function loadAllPages() {
  const pages = [];
  for (const [file, name] of GROUP_FILES) {
    const mod = await import(pathToFileURL(path.join(contentDir, file)).href);
    pages.push(...mod[name]);
  }
  return pages;
}

export async function catalogSource(pages) {
  const entries = pages.map((p) => ({
    path: `/${p.group}/${p.slug}`,
    group: p.group,
    label: p.navLabel,
    blurb: p.navBlurb,
  }));
  const source = `// GENERATED by scripts/gen-catalog.mjs from the page bodies. Do not edit by hand.
import type { ContentGroup } from "./types";

export type CatalogEntry = {
  path: string;
  group: ContentGroup;
  label: string;
  blurb: string;
};

export const CATALOG: CatalogEntry[] = ${JSON.stringify(entries)};
`;
  const options = (await prettier.resolveConfig(OUT)) ?? {};
  return prettier.format(source, { ...options, filepath: OUT });
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const next = await catalogSource(await loadAllPages());
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8").replace(/\r\n/g, "\n") : "";
    if (current !== next) {
      console.error("✗ src/content/catalog.gen.ts is stale: run node scripts/gen-catalog.mjs");
      process.exit(1);
    }
    console.log("✓ catalog.gen.ts is in sync with the page bodies");
  } else {
    fs.writeFileSync(OUT, next);
    console.log(`wrote ${path.relative(root, OUT)}`);
  }
}
